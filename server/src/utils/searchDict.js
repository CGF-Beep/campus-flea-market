/** 统一小写去空格，保证词典命中稳定（查询侧与词典侧共用同一套归一化） */
function normalize(input) {
  return String(input == null ? '' : input).trim().toLowerCase();
}

/**
 * 把同义词组拍平成两张 Map。
 *
 * 校验：同一个词不能出现在两个组里 —— 否则 groupId 归属不明确，
 * 扩展结果会随遍历顺序漂移（搜「香水」可能被扩展成化妆品全组）。
 * 这里不做「报错中断」，而是**首组优先 + 收集冲突**，
 * 由调用方在启动时打日志：宁可少一个同义词，也不能让进程起不来。
 *
 * @returns {{byWord: Map<string, number>, byGroup: Map<number, string[]>, conflicts: Array}}
 */
function buildSynonymIndex(groups) {
  const byWord = new Map();
  const byGroup = new Map();
  const conflicts = [];

  groups.forEach((group, index) => {
    const groupId = index + 1;
    for (const raw of group) {
      const word = normalize(raw);
      if (!word) continue;

      const owner = byWord.get(word);
      if (owner !== undefined && owner !== groupId) {
        conflicts.push({ word, kept: owner, ignored: groupId });
        continue;   // 首组优先，后来的忽略
      }

      byWord.set(word, groupId);
      if (!byGroup.has(groupId)) byGroup.set(groupId, []);
      byGroup.get(groupId).push(word);
    }
  });

  return { byWord, byGroup, conflicts };
}

const { byWord: SYNONYM_BY_WORD, byGroup: SYNONYM_BY_GROUP, conflicts: DICTIONARY_CONFLICTS } =
  buildSynonymIndex(SYNONYM_GROUPS);

/** 品类别名（归一化后）→ 配置里的分类名，供运行时解析成真实 categoryId */
const CATEGORY_ALIAS_BY_NAME = (() => {
  const map = new Map();
  for (const [catName, words] of Object.entries(CATEGORY_ALIASES)) {
    const list = [];
    for (const raw of words) {
      const word = normalize(raw);
      if (word) list.push(word);
    }
    map.set(catName, list);
  }
  return map;
})();

// 启动时把词典健康度打出来：改词改错了这里会立刻暴露，不用等搜索出问题才发现
if (DICTIONARY_CONFLICTS.length) {
  const detail = DICTIONARY_CONFLICTS
    .map((c) => `「${c.word}」第 ${c.ignored} 组的配置被忽略（已在第 ${c.kept} 组）`)
    .join('；');
  console.warn(`[searchDict] 同义词组存在重复词条，${detail}`);
}

